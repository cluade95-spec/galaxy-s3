#!/bin/bash
# Reproduce the experimental, computer-only GT-I8200 kernel builds described in
# docs/phase-2-kernel-build.md.  Nothing here touches a phone: it clones source, builds on
# this computer, and compares files.  It never writes to the original (pristine) clone.
#
# Usage:  tools/kernel-build/build-golden-kernel.sh WORKDIR [JOBS]
#   WORKDIR  an empty or new directory whose absolute path is at most 92 characters long
#            (the source directory name is padded so that the whole source path is exactly
#            94 characters, the length of Samsung's build-farm path; see the document).
#   JOBS     parallel make jobs (default: number of CPUs)
#
# Needs (not installed by this script): git, make, gcc (host tools only), perl, python3, tar, gzip,
# sed, bc, curl, a 64-bit x86 Linux host, about 6 GB of free disk, network access to
# github.com and android.googlesource.com.
set -euo pipefail

WORKDIR=$(mkdir -p "${1:?usage: $0 WORKDIR [JOBS]}" && cd "$1" && pwd)
JOBS=${2:-$(nproc)}
HERE=$(cd "$(dirname "$0")" && pwd)

KERNEL_REPO=https://github.com/Koloses/kernel_i8200
KERNEL_COMMIT=44afe4cf6023bf39c18bad72185003a40915fad2
KERNEL_TREE=0eebf6f928a5cc5f58c4c93a0ca67d16a620e0cd
TC_REPO=https://android.googlesource.com/platform/prebuilts/gcc/linux-x86/arm/arm-eabi-4.6
TC_BRANCH=jb-mr1-release
TC_COMMIT=d73a051b1fd1d98f5c2463354fb67898f0090bdb
TC_BANNER='4.6.x-google 20120106 (prerelease)'
DEFCONFIG=pxa986_golden_rev02_defconfig
# Reference image (community-provided, origin unverified; see the document).
REF_URL=https://raw.githubusercontent.com/Koloses/device_i8200/3bcf4bbe54cb6e9be973fcd88084eb59ef458623/kernel
REF_SHA256=52795a2e64095cd525b27afdd56f4b601dfd8d9ba6e542088ef70c8bc2650860
STOCK_PATH='/home/se.infra/jenkins1/workspace/HUDSON_JELLYBEANPLUS_GOLDENVESS3G_EUR-XX_USER/android/kernel'

log() { printf '\n== %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

for t in git make gcc perl python3 tar gzip sed bc curl; do command -v "$t" >/dev/null || die "missing tool: $t"; done
[ "$(uname -m)" = x86_64 ] || die "the Android 4.2 prebuilt toolchain needs an x86_64 host"

# ---- source directory name padded so the absolute path is exactly 94 characters ----------
want=${#STOCK_PATH}
pad=$(( want - ${#WORKDIR} - 1 ))
[ "$pad" -ge 1 ] || die "WORKDIR path too long (${#WORKDIR} chars); it must be at most $(( want - 2 ))"
SRCNAME=$(printf '%*s' "$pad" '' | tr ' ' k)
SRC=$WORKDIR/$SRCNAME
[ ${#SRC} -eq "$want" ] || die "internal error: source path length ${#SRC} != $want"

# ---- 1. pristine source: exact commit and tree --------------------------------------------
log "1. Pristine source"
[ -d "$WORKDIR/pristine" ] || git clone --no-checkout "$KERNEL_REPO" "$WORKDIR/pristine"
git -C "$WORKDIR/pristine" checkout -q --detach "$KERNEL_COMMIT"
[ "$(git -C "$WORKDIR/pristine" rev-parse HEAD)" = "$KERNEL_COMMIT" ] || die "wrong commit"
[ "$(git -C "$WORKDIR/pristine" rev-parse 'HEAD^{tree}')" = "$KERNEL_TREE" ] || die "tree hash mismatch"
[ -z "$(git -C "$WORKDIR/pristine" status --porcelain)" ] || die "pristine clone is not clean"
echo "commit $KERNEL_COMMIT tree $KERNEL_TREE (verified, clean)"

# ---- 2. original Samsung-era toolchain from AOSP ------------------------------------------
log "2. Toolchain (AOSP $TC_BRANCH)"
[ -d "$WORKDIR/toolchain" ] || git clone --depth 1 --branch "$TC_BRANCH" "$TC_REPO" "$WORKDIR/toolchain"
[ "$(git -C "$WORKDIR/toolchain" rev-parse HEAD)" = "$TC_COMMIT" ] || die "toolchain commit differs from $TC_COMMIT"
CROSS=$WORKDIR/toolchain/bin/arm-eabi-
"${CROSS}gcc" --version | head -1 | grep -qF "$TC_BANNER" || die "toolchain is not $TC_BANNER"
"${CROSS}gcc" --version | head -1
"${CROSS}ld" --version | head -1

# ---- 3. experimental copy: generated build leftovers removed with Kbuild's own cleaner ----
log "3. Experimental copy at $SRC"
if [ ! -d "$SRC" ]; then
  mkdir -p "$SRC"
  (cd "$WORKDIR/pristine" && tar cf - --exclude=.git .) | (cd "$SRC" && tar xf -)
  (cd "$SRC" && make ARCH=arm CROSS_COMPILE="$CROSS" mrproper) > "$WORKDIR/mrproper.log" 2>&1
  (cd "$WORKDIR/pristine" && git ls-files) | while read -r f; do [ -e "$SRC/$f" ] || [ -L "$SRC/$f" ] || echo "$f"; done \
     > "$WORKDIR/deleted-by-mrproper.txt"
  echo "files removed by 'make mrproper' (all generated by Samsung's own earlier build): $(wc -l < "$WORKDIR/deleted-by-mrproper.txt")"
fi

# ---- 4. builds ---------------------------------------------------------------------------
export LC_ALL=C TMPDIR=$WORKDIR/tmp
mkdir -p "$TMPDIR"
cp "$HERE/perl-shim.sh" "$WORKDIR/perl-shim.sh"; chmod +x "$WORKDIR/perl-shim.sh"

build_variant() {  # name, ship(yes/no), metadata(none/stock)
  local name=$1 ship=$2 meta=$3 out=$WORKDIR/out-$1 extra=()
  log "4.$name build (ship options: $ship, metadata: $meta)"
  mkdir -p "$out"
  ( cd "$SRC"
    make O="$out" ARCH=arm CROSS_COMPILE="$CROSS" HOSTCC=gcc "$DEFCONFIG"
    if [ "$ship" = yes ]; then
      # The same five options Samsung's own kernel/Android.mk enables when SEC_PRODUCT_SHIP=true
      scripts/config --file "$out/.config" --enable CONFIG_SAMSUNG_PRODUCT_SHIP \
         --enable CONFIG_SEC_RESTRICT_ROOTING --enable CONFIG_SEC_RESTRICT_SETUID \
         --enable CONFIG_SEC_RESTRICT_FORK --enable CONFIG_SEC_RESTRICT_ROOTING_LOG
    fi
    make O="$out" ARCH=arm CROSS_COMPILE="$CROSS" HOSTCC=gcc silentoldconfig
    if [ "$meta" = stock ]; then
      export KBUILD_BUILD_USER=se.infra KBUILD_BUILD_HOST=SWDB2803 KBUILD_BUILD_VERSION=2
      export KBUILD_BUILD_TIMESTAMP='Wed Mar 18 09:23:47 KST 2015'
      extra=(LOCALVERSION=-2825398)
    else
      export KBUILD_BUILD_USER=experimental KBUILD_BUILD_HOST=goldenvess3g-exp
      export KBUILD_BUILD_TIMESTAMP='Thu Nov 5 00:00:00 UTC 2026'
    fi
    make -j"$JOBS" O="$out" ARCH=arm CROSS_COMPILE="$CROSS" HOSTCC=gcc PERL="$WORKDIR/perl-shim.sh" "${extra[@]}" zImage
  ) > "$WORKDIR/build-$name.log" 2>&1 || { echo "BUILD $name FAILED; see $WORKDIR/build-$name.log"; tail -20 "$WORKDIR/build-$name.log"; exit 1; }
  sha256sum "$out/arch/arm/boot/zImage" "$out/arch/arm/boot/Image"
}
build_variant A no none
build_variant B yes none
build_variant C yes stock

# ---- 5. comparison with the reference image (optional; needs network) -----------------------
log "5. Comparison with the community-provided stock GT-I8200 kernel image"
curl -fsSL -o "$WORKDIR/reference-kernel" "$REF_URL"
[ "$(sha256sum "$WORKDIR/reference-kernel" | cut -d' ' -f1)" = "$REF_SHA256" ] || die "reference image hash mismatch"
python3 -I - "$WORKDIR" "$SRC" "$STOCK_PATH" <<'PY'
import re, sys, zlib, hashlib
work, src, stock_path = sys.argv[1:4]
def image(zimage):
    d = open(zimage, 'rb').read()
    for m in re.finditer(b'\x1f\x8b\x08', d):
        try: r = zlib.decompressobj(31).decompress(d[m.start():])
        except Exception: continue
        if len(r) > 1_000_000: return r
ref = image(work + '/reference-kernel')
for v in 'ABC':
    img = image(f'{work}/out-{v}/arch/arm/boot/zImage')
    assert len(src) == len(stock_path)
    norm = img.replace(src.encode(), stock_path.encode())   # same-length path text only
    n = min(len(norm), len(ref))
    diff = [i for i in range(n) if norm[i] != ref[i]]
    text_hi = 0x5f0000 - 0x108000                            # .head.text + .text of this kernel
    text_diff = sum(1 for i in diff if i < text_hi)
    print(f'variant {v}: image {len(img)} bytes (reference {len(ref)}); '
          f'build-path occurrences replaced: {img.count(src.encode())}; '
          f'differing bytes after path normalisation: {len(diff)}; in .text: {text_diff}; '
          f'sha256(normalised)={hashlib.sha256(norm).hexdigest()[:16]}')
PY
log "Done. Outputs are in $WORKDIR/out-A, out-B, out-C (not for flashing; never commit them)."
